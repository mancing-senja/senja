export interface Glyph {
  w: number;
  /** Bit rows, LSB = leftmost column. */
  rows: number[];
}

const CACHE = new Map<string, Glyph>();

function build(ch: string): Glyph | null {
  const spec = GLYPHS[ch];
  if (!spec) return null;
  const rowStrs = spec.split('/');
  let w = 0;
  for (const r of rowStrs) w = Math.max(w, r.length);
  const rows: number[] = [];
  for (let y = 0; y < GLYPH_H; y++) {
    const s = rowStrs[y] ?? '';
    let bits = 0;
    for (let x = 0; x < s.length; x++) if (s[x] === '#') bits |= 1 << x;
    rows.push(bits);
  }
  return { w: Math.max(1, w), rows };
}

export function glyph(ch: string): Glyph | null {
  let g = CACHE.get(ch);
  if (g === undefined) {
    const built = build(ch);
    if (!built) {
      CACHE.set(ch, NULL_GLYPH);
      return null;
    }
    g = built;
    CACHE.set(ch, g);
  }
  return g === NULL_GLYPH ? null : g;
}

const NULL_GLYPH: Glyph = { w: 0, rows: [] };

export function textWidth(s: string): number {
  let w = 0;
  for (const ch of s) {
    if (ch === ' ') {
      w += SPACE_W + LETTER_GAP;
      continue;
    }
    const g = glyph(ch);
    w += (g ? g.w : SPACE_W) + LETTER_GAP;
  }
  return Math.max(0, w - LETTER_GAP);
}

/** Wraps to a pixel width, breaking on spaces where possible. */
export function wrapText(s: string, maxW: number): string[] {
  const words = s.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let cur = '';
  for (const word of words) {
    const test = cur ? `${cur} ${word}` : word;
    if (textWidth(test) <= maxW || !cur) {
      cur = test;
    } else {
      lines.push(cur);
      cur = word;
    }
  }
  if (cur) lines.push(cur);
  return lines.length ? lines : [''];
}
